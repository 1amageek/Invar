import ArchitectureCore
import ArchitectureFrontend
import Foundation

/// Offline adapter for literal SwiftPM targets and SwiftWeb local host configuration.
public enum RuntimeDiscovery {
    static let signature = "// Generated by Invar from local source and configuration.\n"

    private struct Runtime {
        let id: String, name: String, role: String, source: [String]
        let entryLink: String
        let httpHost: [String]
        let package: String, postgres: [String], endpoints: [String: [String]]
    }
    private struct WebConfig: Decodable {
        struct App: Decodable { let product: String, module: String, type: String }
        struct Environment: Decodable { let host: String }
        let schemaVersion: Int, application: App, environments: [String: Environment]
    }
    private struct SwiftFile {
        let input: SourceInput, root: SyntaxNode
        func citation(_ node: SyntaxNode) -> String {
            let line = input.bytes[..<node.start].reduce(1) { $0 + ($1 == 10 ? 1 : 0) }
            return "\(input.path):\(line) sha256=\(input.digest)"
        }
        func calls(_ name: String) -> [SyntaxNode] {
            root.descendants(["call_expression"]).filter { node in
                node.namedChildren.first.map(input.text) == name
            }
        }
        func argument(_ name: String, of call: SyntaxNode) -> String? {
            let args = call.children.first(where: { $0.kind == "call_suffix" })?.children.first(where: { $0.kind == "value_arguments" })
            let arg = args?.namedChildren.first { $0.namedChildren.first.map(input.text) == name }
            return arg?.namedChildren.last.map(input.text)
        }

        func hostLaunch(in entry: SyntaxNode, imports: Set<String>) -> (module: String, source: String)? {
            guard imports.contains("import SwiftWebHTTPServerHost"),
                  let body = entry.children.first(where: { $0.kind == "class_body" }) else { return nil }
            for method in body.namedChildren where method.kind == "function_declaration" {
                guard method.child("name").map(input.text) == "main",
                      let function = method.children.first(where: { $0.kind == "function_body" }),
                      let statements = function.namedChildren.first(where: { $0.kind == "statements" }) else { continue }
                for statement in statements.namedChildren {
                    var expression = statement
                    while ["try_expression", "await_expression"].contains(expression.kind),
                          let child = expression.namedChildren.last {
                        expression = child
                    }
                    guard expression.kind == "call_expression", let callee = expression.namedChildren.first.map(input.text),
                          callee.hasSuffix(".run"), imports.contains("import " + callee.dropLast(4)) else { continue }
                    return (String(callee.dropLast(4)), citation(expression))
                }
            }
            return nil
        }

        // Only follow a binding between sibling statements. A conditional or nested
        // declaration cannot establish a connection in an enclosing function.
        func connections() -> (postgres: [String], https: [String: [String]]) {
            var postgres: [String] = [], https: [String: [String]] = [:]
            for block in root.descendants(["statements"]) {
                var configs: [String: String] = [:], requests: [String: (String, String)] = [:]
                for statement in block.namedChildren {
                    let declaration = statement.kind == "property_declaration"
                    let binding = declaration ? statement.child("name").map(input.text) : nil
                    let rhs = declaration ? statement.child("value") : statement
                    guard let rhs else { continue }
                    if let binding { configs.removeValue(forKey: binding); requests.removeValue(forKey: binding) }
                    if rhs.kind == "assignment", let lhs = rhs.namedChildren.first.map(input.text) {
                        configs.removeValue(forKey: lhs)
                        requests.removeValue(forKey: lhs)
                        if lhs.hasSuffix(".url") { requests.removeValue(forKey: String(lhs.dropLast(4))) }
                    }
                    func inspect(_ node: SyntaxNode) {
                        guard ["call_expression","try_expression","await_expression"].contains(node.kind) else { return }
                        if node.kind != "call_expression" { for child in node.namedChildren { inspect(child) }; return }
                        switch node.namedChildren.first.map(input.text) {
                        case "PostgreSQLConfiguration":
                            if let binding { configs[binding] = citation(node) }
                        case "PostgreSQLStorageEngine":
                            if let key = argument("configuration", of: node), let config = configs[key] {
                                postgres += [config, citation(node)]
                            }
                        case "URLRequest":
                            guard let binding, let expr = argument("url", of: node),
                                let match = expr.wholeMatch(of: /^URL\(string:\s*"(?<literal>https:\/\/[^"\\]+)"\)!?$/),
                                let url = URLComponents(string: String(match.literal)), url.user == nil, url.password == nil,
                                let host = url.host?.lowercased(), host.wholeMatch(of: /^[a-z0-9.-]+$/) != nil else { return }
                            requests[binding] = (host, citation(node))
                        case "URLSession.shared.data":
                            if let key = argument("for", of: node), let (host, source) = requests[key] {
                                https[host, default: []] += [source, citation(node)]
                            }
                        default: break
                        }
                    }
                    inspect(rhs)
                }
            }
            return (postgres, https)
        }
    }

    public static func generate(root: URL, system: String, packages: [String]) throws -> [String: String] {
        let base = root.standardizedFileURL.resolvingSymlinksInPath()
        let prefix = base.path + "/"
        let fm = FileManager.default
        func bad(_ message: String) -> ArchitectureError { ArchitectureError("MAP_INPUT_INVALID", message) }
        func safeText(_ value: String) -> Bool {
            !value.contains("${") && !value.isEmpty && value.utf8.count <= 1024 && !value.contains("\"") && !value.contains("\\")
                && value.unicodeScalars.allSatisfy { !CharacterSet.controlCharacters.contains($0) }
        }
        guard safeText(system), (1...64).contains(packages.count) else { throw bad("Invalid system name or package count.") }
        var total = 0, seen = Set<String>(), captured: [URL: String] = [:]
        func read(_ url: URL) throws -> Data {
            let resolved = url.resolvingSymlinksInPath().standardizedFileURL
            guard resolved.path.hasPrefix(prefix), resolved.path == url.standardizedFileURL.path else { throw bad("Input escaped its workspace or followed a symlink.") }
            let attrs = try resolved.resourceValues(forKeys: [.fileSizeKey, .isRegularFileKey])
            guard attrs.isRegularFile == true, let size = attrs.fileSize, size <= 2*1024*1024,
                  total + size <= 32*1024*1024 else { throw bad("Input exceeds file or capture budget.") }
            let data = try Data(contentsOf: resolved)
            guard data.count == size else { throw bad("Input changed during capture.") }
            total += size
            captured[resolved] = CanonicalJSON.digest(data)
            return data
        }
        func parse(_ url: URL, bytes data: Data) throws -> SwiftFile {
            let path = String(url.path.dropFirst(prefix.count))
            guard safeText(path) else { throw bad("Unsupported path characters.") }
            let input = SourceInput(workspaceID: "", path: path, language: "swift", bytes: data, contextDigest: "", generation: 0)
            return try SwiftFile(input: input, root: SyntaxParser().parse(input))
        }
        func scanSources(_ directory: URL, visit: (URL) throws -> Void) throws {
            var failure: Error?
            guard let files = fm.enumerator(at: directory, includingPropertiesForKeys: [.isSymbolicLinkKey],
                options: [.skipsHiddenFiles], errorHandler: { _, error in failure = error; return false }) else {
                throw bad("Cannot enumerate sources in \(directory.lastPathComponent).")
            }
            for case let file as URL in files {
                try Task.checkCancellation()
                if try file.resourceValues(forKeys: [.isSymbolicLinkKey]).isSymbolicLink == true { files.skipDescendants(); continue }
                if file.pathExtension == "swift" { try visit(file) }
            }
            if let failure { throw failure }
        }
        var runtimes: [Runtime] = []
        for package in packages.sorted() {
            try Task.checkCancellation()
            guard !package.hasPrefix("/"), !package.split(separator: "/").contains("..") else { throw bad("Expected relative package paths.") }
            let dir = base.appendingPathComponent(package).standardizedFileURL
            guard seen.insert(dir.path).inserted else { throw bad("Duplicate package path.") }
            let manifestURL = dir.appendingPathComponent("Package.swift")
            let manifestBytes = try read(manifestURL)
            let manifest = try parse(manifestURL, bytes: manifestBytes)
            let configURL = dir.appendingPathComponent("sweb.json")
            var config: WebConfig?, configRef: String?
            if fm.fileExists(atPath: configURL.path) {
                let bytes = try read(configURL)
                let decoded = try JSONDecoder().decode(WebConfig.self, from: bytes)
                guard decoded.schemaVersion == 2 else { throw bad("Unsupported SwiftWeb configuration version.") }
                if decoded.environments["local"]?.host == "swift-web/http-server" {
                    config = decoded
                    configRef = "\(String(configURL.path.dropFirst(prefix.count))) sha256=\(CanonicalJSON.digest(bytes))"
                }
            }
            if let config {
                let product = config.application.product, module = config.application.module
                let matches = (manifest.calls(".library") + manifest.calls(".executable")).filter { decl in
                    manifest.argument("name", of: decl) == "\"\(product)\"" &&
                        manifest.argument("targets", of: decl)?.wholeMatch(of: /^\[\s*"(?<target>[A-Za-z0-9_]+)"\s*\]$/)?.target == module[...]
                }
                guard matches.count == 1 else { throw bad("Unresolved SwiftWeb product or module.") }
            }
            let targets = manifest.calls(".executableTarget") + (config == nil ? [] : manifest.calls(".target"))
            var matchedWeb = false
            for target in targets {
                let executable = target.namedChildren.first.map(manifest.input.text) == ".executableTarget"
                guard let literal = manifest.argument("name", of: target), literal.hasPrefix("\""), literal.hasSuffix("\"") else {
                    throw bad("Map requires a literal SwiftPM target name.")
                }
                let name = String(literal.dropFirst().dropLast())
                guard name.range(of: #"^[A-Za-z_][A-Za-z0-9_]*$"#, options: .regularExpression) != nil else { throw bad("Unsupported target name.") }
                let web = config?.application.module == name
                guard executable || web else { continue }
                matchedWeb = matchedWeb || web
                // A nonstandard target layout must not silently resolve different sources.
                guard ["path","sources","exclude"].allSatisfy({ manifest.argument($0, of: target) == nil }) else {
                    throw bad("Custom sources, excludes and paths require an explicit adapter for \(name).")
                }
                let directory = dir.appendingPathComponent("Sources").appendingPathComponent(name)
                var entry: (citation: String, link: String)?, storage: [String] = [], endpoints: [String: [String]] = [:]
                var hostLaunch: (module: String, source: String)?
                try scanSources(directory) { file in
                    let bytes = try read(file)
                    let candidates = ["main", "URLSession", "PostgreSQLStorage", "SwiftWebHTTPServerHost"] + (web ? [config!.application.type] : [])
                    guard candidates.contains(where: { bytes.range(of: Data($0.utf8)) != nil }) else { return }
                    let parsed = try parse(file, bytes: bytes)
                    let imports = Set(parsed.root.descendants(["import_declaration"]).map(parsed.input.text))
                    for decl in parsed.root.namedChildren where decl.kind == "class_declaration" {
                        let attrs = decl.children.first { $0.kind == "modifiers" }?.descendants(["attribute"]).map(parsed.input.text) ?? []
                        let main = executable && attrs.contains("@main")
                        let isApp = web && decl.child("name").map(parsed.input.text) == config?.application.type &&
                            decl.children.contains { $0.kind == "inheritance_specifier" && parsed.input.text($0) == "SwiftWeb.App" }
                        if main || isApp {
                            guard entry == nil else { throw bad("Ambiguous runtime entry in \(name).") }
                            let kind = decl.child("declaration_kind")?.kind == "actor" ? "actor" : "type"
                            let link = "\(kind) \(decl.start)..<\(decl.end) sha256=\(parsed.input.digest) \(parsed.input.path)"
                            entry = (parsed.citation(decl), link)
                            if main { hostLaunch = parsed.hostLaunch(in: decl, imports: imports) }
                        }
                    }
                    let connections = parsed.connections()
                    if imports.contains("import PostgreSQLStorage") { storage += connections.postgres }
                    for (host, refs) in connections.https { endpoints[host, default: []] += refs }

                }
                guard let entry else { throw bad("Cannot resolve runtime entry for \(name).") }
                let id = "app_" + CanonicalJSON.digest(manifest.input.path + "/" + name).prefix(16)
                let refs = [manifest.citation(target), entry.citation] + (web ? [configRef].compactMap { $0 } : [])
                var httpHost = web ? refs : []
                if let launch = hostLaunch,
                   let module = manifest.calls(".target").first(where: { manifest.argument("name", of: $0) == "\"\(launch.module)\"" }),
                   ["path","sources","exclude"].allSatisfy({ manifest.argument($0, of: module) == nil }) {
                    let moduleDir = dir.appendingPathComponent("Sources").appendingPathComponent(launch.module)
                    var declarations: [String] = []
                    try scanSources(moduleDir) { file in
                        let bytes = try read(file)
                        guard bytes.range(of: Data("SwiftWeb".utf8)) != nil else { return }
                        let parsed = try parse(file, bytes: bytes)
                        for declaration in parsed.root.namedChildren where declaration.kind == "class_declaration" &&
                            declaration.child("name").map(parsed.input.text) == launch.module &&
                            declaration.children.contains(where: { $0.kind == "inheritance_specifier" && parsed.input.text($0) == "SwiftWeb.App" }) {
                            declarations.append(parsed.citation(declaration))
                        }
                    }
                    if declarations.count == 1 { httpHost = [launch.source, manifest.citation(module)] + declarations }
                }
                runtimes.append(Runtime(id: id, name: name, role: httpHost.isEmpty ? "worker" : "website",
                    source: refs, entryLink: entry.link, httpHost: httpHost, package: String(manifest.input.path.dropLast("Package.swift".count))
                        .trimmingCharacters(in: CharacterSet(charactersIn: "/")), postgres: storage.sorted(), endpoints: endpoints))

            }
            guard config == nil || matchedWeb else { throw bad("Configured SwiftWeb target is missing.") }
        }
        guard !runtimes.isEmpty else { throw bad("No supported runtime declarations.") }
        let byName = Dictionary(grouping: runtimes, by: \.name)
        func label(_ r: Runtime) -> String {
            let peers = byName[r.name, default: []]
            guard peers.count > 1 else { return r.name }
            let leaf = (r.package as NSString).lastPathComponent
            let unique = peers.filter { ($0.package as NSString).lastPathComponent == leaf }.count == 1
            return "\(unique ? leaf : r.package) / \(r.name)"
        }
        func endpointID(_ host: String) -> String { "https_" + CanonicalJSON.digest(host).prefix(16) }
        // Recheck the exact files used, before publishing any part of the workspace.
        for (url, digest) in captured {
            guard url.resolvingSymlinksInPath().path == url.path,
                  try url.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? Int.max <= 2*1024*1024,
                  try CanonicalJSON.digest(Data(contentsOf: url)) == digest else { throw bad("Input changed during generation.") }
        }
        var lines = [signature.trimmingCharacters(in: .newlines), "workspace \"\(system)\" {", "    !impliedRelationships false", "    model {"]
        func evidence(_ refs: [String], indent: String) { lines += refs.map { indent + "// Source: " + $0 } }
        func external(domain: String, declaration: String, sources: [String]) {
            lines.append("        group \"\(domain)\" {")
            evidence(sources, indent: "            ")
            lines.append("            " + declaration)
            lines.append("        }")
        }
        let sorted = runtimes.sorted { $0.id < $1.id }
        let inbound = sorted.filter { !$0.httpHost.isEmpty }
        if !inbound.isEmpty {
            external(domain: "Unresolved callers",
                declaration: "http_client = softwareSystem \"HTTP client (unspecified)\" \"Logical caller role for exposed HTTP interfaces. Client identity and traffic are unknown.\"",
                sources: inbound.flatMap(\.httpHost))
        }
        let hosts = Set(sorted.flatMap { $0.endpoints.keys }).sorted()
        for host in hosts {
            external(domain: "Remote service · \(host)",
                declaration: "\(endpointID(host)) = softwareSystem \"\(host)\" \"HTTPS endpoint used by the selected implementation\"",
                sources: sorted.flatMap { $0.endpoints[host] ?? [] }.sorted())
        }
        for r in sorted where !r.postgres.isEmpty {
            external(domain: "Unresolved storage · \(label(r))",
                declaration: "db_\(r.id) = softwareSystem \"PostgreSQL for \(label(r))\" \"Logical endpoint outside the selected Swift runtime boundary. Physical database identity is unresolved.\" \"Database\"",
                sources: r.postgres)
        }
        lines.append("        group \"Local runtimes\" {")
        lines.append("            subject = softwareSystem \"\(system)\" \"Selected local development runtimes\" {")
        let grouped = Dictionary(grouping: sorted, by: \.package)
        var files: [String: String] = [:]
        var relations: [String: [String]] = [:]
        func fragment(_ package: String, _ name: String) -> String {
            package.isEmpty ? name : package + "/" + name
        }
        func store(_ body: [String], at path: String, indent: String) {
            files[path] = signature + body.joined(separator: "\n") + "\n"
            lines.append(indent + "!include \"" + path + "\"")
        }
        for package in grouped.keys.sorted() {
            var body: [String] = []
            for r in grouped[package, default: []] {
                body.append("// Entry: " + r.entryLink)
                body += r.source.map { "// Source: " + $0 }
                body.append("\(r.id) = container \"\(label(r))\" \"Configured Swift runtime\" \"Swift\" \"\(r.role)\"")
            }
            store(body, at: fragment(package, "containers.dsl"), indent: "                ")
        }
        func interaction(_ r: Runtime, _ sources: [String], _ statement: String) {
            relations[r.package, default: []] += sources.map { "// Source: " + $0 } + [statement]
        }
        lines += ["            }", "        }"]
        if !inbound.isEmpty {
            evidence(inbound.flatMap(\.httpHost), indent: "        ")
            lines.append("        http_client -> subject \"Can send requests to exposed hosts\" \"HTTP\"")
            for runtime in inbound {
                interaction(runtime, runtime.httpHost, "http_client -> \(runtime.id) \"Can send HTTP requests\" \"HTTP\"")
            }
        }
        for r in sorted where !r.postgres.isEmpty {
            evidence(r.source + r.postgres, indent: "        ")
            lines.append("        subject -> db_\(r.id) \"Configures PostgreSQL access via \(label(r))\" \"PostgreSQL\"")
            interaction(r, r.postgres, "\(r.id) -> db_\(r.id) \"Creates a PostgreSQL storage engine\" \"PostgreSQL\"")
        }
        for host in hosts {
            let consumers = sorted.filter { $0.endpoints[host] != nil }
            evidence(consumers.flatMap { $0.endpoints[host] ?? [] }.sorted(), indent: "        ")
            lines.append("        subject -> \(endpointID(host)) \"Sends HTTPS requests\" \"HTTPS\"")
            for r in consumers {
                interaction(r, r.endpoints[host, default: []].sorted(), "\(r.id) -> \(endpointID(host)) \"Sends HTTPS requests\" \"HTTPS\"")
            }
        }
        for package in relations.keys.sorted() {
            store(relations[package, default: []], at: fragment(package, "relationships.dsl"), indent: "        ")
        }
        lines += ["    }", "    views {"]
        for (kind, key) in [("systemContext","Context"),("container","Containers")] {
            lines += ["        \(kind) subject \(key) {", "            include *", "        }"]
        }
        let result = (lines + ["    }", "}", ""]).joined(separator: "\n")
        files[WorkspacePaths.architectureModelFilename] = result
        guard files.values.reduce(0, { $0 + $1.utf8.count }) <= 512 * 1024 else { throw bad("Generated DSL exceeds the Map input budget.") }
        return files
    }
}
