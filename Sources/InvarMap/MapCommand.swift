import ArchitectureCore
import Foundation
import Darwin

public enum MapCommand {
    public static func run(_ arguments: [String]) throws {
        let usage = "invar map --workspace DIR --system NAME --package RELATIVE_DIR [--package DIR ...] [--out FILE]"
        var options: [String: String] = [:], packages: [String] = []
        guard arguments.count.isMultiple(of: 2) else { throw ArchitectureError("INVALID_ARGUMENT", usage) }
        for index in stride(from: 0, to: arguments.count, by: 2) {
            let key = arguments[index], value = arguments[index + 1]
            if key == "--package" { packages.append(value); continue }
            guard ["--workspace", "--system", "--out"].contains(key), options[key] == nil else {
                throw ArchitectureError("INVALID_ARGUMENT", usage)
            }
            options[key] = value
        }
        guard let path = options["--workspace"], let system = options["--system"], !packages.isEmpty else {
            throw ArchitectureError("INVALID_ARGUMENT", usage)
        }
        let root = URL(fileURLWithPath: path).standardizedFileURL.resolvingSymlinksInPath()
        if let destination = options["--out"] {
            let url = URL(fileURLWithPath: destination).standardizedFileURL
            guard url.deletingLastPathComponent().resolvingSymlinksInPath().path == root.path,
                url.lastPathComponent == WorkspacePaths.architectureModelFilename else {
                throw ArchitectureError("INVALID_ARGUMENT", "Map output must be \(WorkspacePaths.architectureModelFilename) at the workspace root.")
            }
        }
        let files = try RuntimeDiscovery.generate(root: root, system: system, packages: packages)
        try write(files, to: root)
    }

    private static func write(_ files: [String: String], to root: URL) throws {
        let directory = open(root.path, O_RDONLY | O_DIRECTORY | O_CLOEXEC)
        guard directory >= 0 else { throw ArchitectureError("OUTPUT_CONFLICT", "Cannot open the Map workspace.") }
        defer { close(directory) }
        guard flock(directory, LOCK_EX) == 0 else { throw ArchitectureError("OUTPUT_CONFLICT", "Cannot lock the workspace.") }
        let order = files.keys.filter { $0 != WorkspacePaths.architectureModelFilename }.sorted() + [WorkspacePaths.architectureModelFilename]
        var previous: [String: Data] = [:]
        let sig = Data(RuntimeDiscovery.signature.utf8)
        for path in order {
            let url = root.appendingPathComponent(path)
            guard url.deletingLastPathComponent().resolvingSymlinksInPath().path == url.deletingLastPathComponent().path else {
                throw ArchitectureError("OUTPUT_CONFLICT", "Symlinked output directory: " + path)
            }
            var info = stat()
            if lstat(url.path, &info) == 0 {
                guard info.st_mode & S_IFMT == S_IFREG, info.st_size <= 512 * 1024 else {
                    throw ArchitectureError("OUTPUT_CONFLICT", "Unexpected output file: " + path)
                }
                let bytes = try Data(contentsOf: url)
                guard bytes.starts(with: sig) else { throw ArchitectureError("OUTPUT_CONFLICT", "Existing DSL was not generated by Invar: " + path) }
                previous[path] = bytes
            } else if errno != ENOENT { throw ArchitectureError("OUTPUT_CONFLICT", "Cannot inspect output: " + path) }
        }
        var written: [String] = []
        do {
            for path in order {
                let bytes = Data(files[path]!.utf8)
                if bytes != previous[path] {
                    try bytes.write(to: root.appendingPathComponent(path), options: .atomic)
                    written.append(path)
                }
            }
        } catch {
            for path in written.reversed() {
                let url = root.appendingPathComponent(path)
                if let original = previous[path] { try original.write(to: url, options: .atomic) }
                else { try FileManager.default.removeItem(at: url) }
            }
            throw error
        }
    }
}
